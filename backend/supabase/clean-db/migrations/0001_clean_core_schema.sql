CREATE TABLE public.inventory_locations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  branch_id integer REFERENCES public.branches(id),
  location_code text NOT NULL,
  name text NOT NULL,
  location_type text NOT NULL CHECK (location_type IN ('central_store', 'branch_store', 'department', 'pos_outlet', 'production', 'supplier', 'waste', 'in_transit')),
  parent_location_id uuid REFERENCES public.inventory_locations(id),
