CREATE TABLE public.inventory_batches (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  item_id uuid NOT NULL REFERENCES public.inventory_items(id),
  batch_number text NOT NULL,
  lot_number text,
  supplier_id uuid,
  expiry_date date,
  manufacture_date date,
  unit_cost numeric(14,4) NOT NULL DEFAULT 0,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT NOW(),
  UNIQUE (item_id, batch_number)
);

CREATE TABLE public.inventory_balances (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  item_id uuid NOT NULL REFERENCES public.inventory_items(id),
  location_id uuid NOT NULL REFERENCES public.inventory_locations(id),
  batch_id uuid REFERENCES public.inventory_batches(id),
  current_quantity numeric(14,3) NOT NULL DEFAULT 0 CHECK (current_quantity >= 0),
  reserved_quantity numeric(14,3) NOT NULL DEFAULT 0 CHECK (reserved_quantity >= 0),
  damaged_quantity numeric(14,3) NOT NULL DEFAULT 0 CHECK (damaged_quantity >= 0),
  expired_quantity numeric(14,3) NOT NULL DEFAULT 0 CHECK (expired_quantity >= 0),
  available_quantity numeric(14,3) GENERATED ALWAYS AS (current_quantity - reserved_quantity - damaged_quantity - expired_quantity) STORED,
  unit_cost numeric(14,4) NOT NULL DEFAULT 0,
  last_movement_id uuid,
  created_at timestamptz NOT NULL DEFAULT NOW(),
  updated_at timestamptz NOT NULL DEFAULT NOW(),
  CHECK (reserved_quantity + damaged_quantity + expired_quantity <= current_quantity),
  UNIQUE (item_id, location_id, batch_id)
);

CREATE TABLE public.inventory_movements (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  movement_number text NOT NULL UNIQUE,
  branch_id integer REFERENCES public.branches(id),
  movement_type text NOT NULL CHECK (movement_type IN (
    'purchase_receipt', 'grn_posting', 'branch_requisition_dispatch',
    'central_store_packing', 'department_issue', 'pos_issue',
    'production_consumption', 'production_output', 'stock_take_adjustment',
    'return', 'write_off', 'transfer', 'reservation', 'reservation_release',
    'sale_consumption', 'wastage'
  )),
  item_id uuid NOT NULL REFERENCES public.inventory_items(id),
  batch_id uuid REFERENCES public.inventory_batches(id),
  source_location_id uuid REFERENCES public.inventory_locations(id),
  destination_location_id uuid REFERENCES public.inventory_locations(id),
  quantity numeric(14,3) NOT NULL CHECK (quantity > 0),
  unit_cost numeric(14,4) NOT NULL DEFAULT 0,
  reason text NOT NULL,
  document_type text NOT NULL,
  document_id uuid,
  document_number text NOT NULL,
  actor_id uuid REFERENCES public.users(id),
  reversible boolean NOT NULL DEFAULT true,
  reversed_by_movement_id uuid REFERENCES public.inventory_movements(id),
  before_balance jsonb,
  after_balance jsonb,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT NOW(),
  CHECK (source_location_id IS NOT NULL OR destination_location_id IS NOT NULL)
);

ALTER TABLE public.inventory_balances
  ADD CONSTRAINT inventory_balances_last_movement_fk
  FOREIGN KEY (last_movement_id) REFERENCES public.inventory_movements(id);

CREATE TABLE public.inventory_reservations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  reservation_number text NOT NULL UNIQUE,
  branch_id integer REFERENCES public.branches(id),
  item_id uuid NOT NULL REFERENCES public.inventory_items(id),
  location_id uuid NOT NULL REFERENCES public.inventory_locations(id),
  quantity numeric(14,3) NOT NULL CHECK (quantity > 0),
  fulfilled_quantity numeric(14,3) NOT NULL DEFAULT 0 CHECK (fulfilled_quantity >= 0),
  status text NOT NULL DEFAULT 'reserved' CHECK (status IN ('reserved', 'released', 'fulfilled', 'expired', 'cancelled')),
  source_document_type text NOT NULL,
  source_document_id uuid NOT NULL,
  source_document_number text NOT NULL,
  reserved_by uuid REFERENCES public.users(id),
  expires_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT NOW(),
  updated_at timestamptz NOT NULL DEFAULT NOW(),
  CHECK (fulfilled_quantity <= quantity)
);

CREATE TABLE public.inventory_alerts (
