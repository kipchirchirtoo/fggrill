-- FamousGate Hotels clean database core schema
-- Target: brand-new Supabase/PostgreSQL project only.
-- Do not run this against the existing dirty production database.

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE SCHEMA IF NOT EXISTS legacy_import;

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS trigger AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION public.current_branch_id()
RETURNS integer AS $$
  SELECT NULLIF(current_setting('request.jwt.claims', true)::jsonb->>'branch_id', '')::integer;
$$ LANGUAGE sql STABLE;

CREATE OR REPLACE FUNCTION public.current_user_uuid()
RETURNS uuid AS $$
  SELECT NULLIF(current_setting('request.jwt.claims', true)::jsonb->>'sub', '')::uuid;
$$ LANGUAGE sql STABLE;

