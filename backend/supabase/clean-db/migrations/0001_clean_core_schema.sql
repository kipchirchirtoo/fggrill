CREATE TABLE public.branches (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  code text NOT NULL UNIQUE,
  location text NOT NULL,
  legal_name text,
  email text,
  phone text,
  address text,
  city text,
