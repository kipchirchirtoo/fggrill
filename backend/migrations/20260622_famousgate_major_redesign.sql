-- 7. PAYMENTS DEDUPLICATION
--    DEVIATION: the live generic `payments` table is a hotel booking/folio
--    ledger (booking_id, folio_id) with no shift_id or pos_transaction_id
--    columns — it is not where cashier/POS duplicates occur. The table that
--    actually has shift_id + a transaction reference + payment_method + amount
--    is `cashier_shift_transactions` (transaction_id stands in for
--    pos_transaction_id). Retargeting this entire section to it.
--
--    DEVIATION: existing rows predate any source tagging, so "keep the
--    cashier-sourced record, delete the POS duplicate" can only be applied
--    going forward once `source` is populated by the app. For the one-time
--    cleanup of existing duplicates, the dedup below prefers a row tagged
--    source = 'cashier' over 'pos' when both exist for the same
--    (shift_id, transaction_id, payment_method, amount) tuple, and otherwise
--    falls back to keeping the lowest id (oldest row) since provenance is
--    unknown for legacy data.
-- =====================================================================

-- Diagnostic: show duplicate payment rows before touching anything
SELECT shift_id, transaction_id, payment_method, amount, COUNT(*)
FROM cashier_shift_transactions
GROUP BY shift_id, transaction_id, payment_method, amount
HAVING COUNT(*) > 1;

ALTER TABLE cashier_shift_transactions
ADD COLUMN IF NOT EXISTS source TEXT CHECK (source IN ('cashier','pos'));

-- Run this DELETE before adding the unique constraint below.
WITH ranked AS (
  SELECT
    id,
    ROW_NUMBER() OVER (
      PARTITION BY shift_id, transaction_id, payment_method, amount
      ORDER BY
        CASE source WHEN 'cashier' THEN 0 WHEN 'pos' THEN 1 ELSE 2 END,
        id
    ) AS rn
  FROM cashier_shift_transactions
)
DELETE FROM cashier_shift_transactions cst
USING ranked
WHERE cst.id = ranked.id
  AND ranked.rn > 1;

ALTER TABLE cashier_shift_transactions
ADD CONSTRAINT uq_cst_shift_txn_method_amount
  UNIQUE (shift_id, transaction_id, payment_method, amount);


