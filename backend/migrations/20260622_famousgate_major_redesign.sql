-- 13. NON-SALE STOCK OUT TRACKING
--     DEVIATION: stock_out_lines does not exist — and the closest live name,
--     stock_out_records, is a VIEW (see header note), so the new columns and
--     trigger below target the real base table, branch_stock_movements,
--     which already has item_id UUID directly (item_code/item_sku lookup is
--     only a fallback). The trigger guards on the same "is this an
--     out-movement" predicate the view uses, since branch_stock_movements
--     also stores stock-IN rows that must not be flagged.
--     DEVIATION: inventory_items has no is_for_sale column — adding it here.
--     Defaulting to TRUE so existing sellable catalogue items are not
--     retroactively misflagged as operational expenses; items that are
--     genuinely non-sale (cleaning supplies, internal-use stock, etc.) need a
--     manual UPDATE to set is_for_sale = false after this migration runs.
-- =====================================================================

ALTER TABLE inventory_items
ADD COLUMN IF NOT EXISTS is_for_sale BOOLEAN DEFAULT true;

ALTER TABLE branch_stock_movements
ADD COLUMN IF NOT EXISTS is_operational_expense BOOLEAN DEFAULT false,
ADD COLUMN IF NOT EXISTS line_cost NUMERIC(12,2);

CREATE OR REPLACE FUNCTION fn_flag_operational_expense()
RETURNS TRIGGER AS $$
DECLARE
  v_is_out_movement BOOLEAN;
BEGIN
  v_is_out_movement := (
    NEW.quantity < 0
    OR lower(COALESCE(NEW.movement_type, '')) = ANY (ARRAY['stock_out','out','issue','department_issue','pos_issue','kitchen_issue','usage'])
  );
  IF NOT v_is_out_movement THEN
    RETURN NEW;
  END IF;

  IF EXISTS (
    SELECT 1 FROM inventory_items
    WHERE (id = NEW.item_id OR item_code = NEW.item_sku) AND is_for_sale = false
  ) THEN
    NEW.is_operational_expense := true;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_flag_operational_expense ON branch_stock_movements;
CREATE TRIGGER trg_flag_operational_expense
BEFORE INSERT ON branch_stock_movements
FOR EACH ROW EXECUTE FUNCTION fn_flag_operational_expense();

