-- 10. STOCK BALANCE LEDGER
--     DEVIATION: branch_id corrected to INTEGER; item_id corrected to UUID
--     REFERENCES inventory_items(id) — confirmed live (see header note).
--     DEVIATION: grn_items/goods_received_notes do not exist. The real
--     receiving-line table is goods_receipt_lines (FK column goods_receipt_id
--     -> goods_receipts.id), which already carries item_id (UUID) and
--     quantity_received directly; goods_receipts already has its own
--     branch_id (INTEGER) — no join through purchase_orders is needed at all,
--     unlike the original grn_items-based draft.
--     DEVIATION: an earlier pass of this file also attached a second copy of
--     this trigger to `store_grn_items`, believing it was a separate receiving
--     flow. It is not — store_grn_items is a plain view over goods_receipt_lines
--     (confirmed via pg_views), and Postgres does not allow row-level triggers
--     on views at all (`ERROR 42809: "store_grn_items" is a view`). Removed;
--     the single trigger on goods_receipt_lines below already fires for inserts
--     made through the store_grn_items view too, since it's a simple,
--     unfiltered, single-table view and Postgres forwards inserts through such
--     views to the underlying base table automatically.
--     DEVIATION: "stock_out_lines" = branch_stock_movements (the real table
--     behind the stock_out_records view — see header note), which stores
--     BOTH stock-in and stock-out rows with a SIGNED quantity (negative for
--     outs), and already has item_id UUID directly. fn_update_ledger_on_issue
--     attaches to branch_stock_movements (not the view — views can't have row
--     triggers) and guards on the same "is this an out-movement" predicate
--     the view uses, using abs(quantity) as the issued amount and falling
--     back to an item_code lookup only if item_id is ever null.
-- =====================================================================

CREATE TABLE IF NOT EXISTS stock_balance_ledger (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  branch_id INTEGER NOT NULL REFERENCES branches(id),
  item_id UUID NOT NULL REFERENCES inventory_items(id),
  ledger_date DATE NOT NULL DEFAULT CURRENT_DATE,
  opening_balance NUMERIC(12,3) NOT NULL DEFAULT 0,
  additional_stock NUMERIC(12,3) NOT NULL DEFAULT 0,
  issued_stock NUMERIC(12,3) NOT NULL DEFAULT 0,
  closing_balance NUMERIC(12,3) GENERATED ALWAYS AS (opening_balance + additional_stock - issued_stock) STORED,
  actual_closing NUMERIC(12,3),
  variance NUMERIC(12,3),
  UNIQUE(branch_id, item_id, ledger_date)
);

CREATE OR REPLACE FUNCTION fn_update_ledger_on_receive_goods_receipt()
RETURNS TRIGGER AS $$
DECLARE
  v_branch_id INTEGER;
BEGIN
  SELECT branch_id INTO v_branch_id FROM goods_receipts WHERE id = NEW.goods_receipt_id;
  IF v_branch_id IS NULL THEN
    RETURN NEW;
  END IF;

  INSERT INTO stock_balance_ledger (branch_id, item_id, ledger_date, additional_stock)
  VALUES (v_branch_id, NEW.item_id, CURRENT_DATE, NEW.quantity_received)
  ON CONFLICT (branch_id, item_id, ledger_date)
  DO UPDATE SET additional_stock = stock_balance_ledger.additional_stock + EXCLUDED.additional_stock;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_goods_receipt_lines_update_ledger ON goods_receipt_lines;
CREATE TRIGGER trg_goods_receipt_lines_update_ledger
AFTER INSERT ON goods_receipt_lines
FOR EACH ROW EXECUTE FUNCTION fn_update_ledger_on_receive_goods_receipt();

CREATE OR REPLACE FUNCTION fn_update_ledger_on_issue()
RETURNS TRIGGER AS $$
DECLARE
  v_item_id UUID;
  v_is_out_movement BOOLEAN;
BEGIN
  v_is_out_movement := (
    NEW.quantity < 0
    OR lower(COALESCE(NEW.movement_type, '')) = ANY (ARRAY['stock_out','out','issue','department_issue','pos_issue','kitchen_issue','usage'])
  );
  IF NOT v_is_out_movement THEN
    RETURN NEW;
  END IF;

  v_item_id := NEW.item_id;
  IF v_item_id IS NULL THEN
    SELECT id INTO v_item_id FROM inventory_items WHERE item_code = NEW.item_sku;
  END IF;
  IF v_item_id IS NULL THEN
    RETURN NEW;
  END IF;

  INSERT INTO stock_balance_ledger (branch_id, item_id, ledger_date, issued_stock)
  VALUES (NEW.branch_id, v_item_id, CURRENT_DATE, abs(NEW.quantity))
  ON CONFLICT (branch_id, item_id, ledger_date)
  DO UPDATE SET issued_stock = stock_balance_ledger.issued_stock + EXCLUDED.issued_stock;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_branch_stock_movements_update_ledger ON branch_stock_movements;
CREATE TRIGGER trg_branch_stock_movements_update_ledger
AFTER INSERT ON branch_stock_movements
FOR EACH ROW EXECUTE FUNCTION fn_update_ledger_on_issue();


