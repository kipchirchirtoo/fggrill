-- 8. VOID ITEMS COLUMN
--    DEVIATION: the bill line items table is restaurant_order_items
--    (order_id, menu_item_id, quantity, unit_price, total_price), joined to
--    restaurant_menu_items for the item name (restaurant_order_items has no
--    item_name column of its own). void_requests.order_id is the join key.
-- =====================================================================

ALTER TABLE void_requests
ADD COLUMN IF NOT EXISTS void_items JSONB DEFAULT '[]'::jsonb;

COMMENT ON COLUMN void_requests.void_items IS
'Array of {item_id, item_name, quantity, unit_price, line_total} populated at void request creation time';

-- Backfill: best-effort reconstruction for existing void_requests from the
-- order's line items at the time of backfill (not necessarily the exact lines
-- that were voided, since void_requests does not currently record which
-- specific lines were voided — this is the closest available reconstruction).
UPDATE void_requests vr
SET void_items = backfill.items
FROM (
  SELECT
    roi.order_id,
    jsonb_agg(
      jsonb_build_object(
        'item_id', roi.menu_item_id,
        'item_name', rmi.name,
        'quantity', roi.quantity,
        'unit_price', roi.unit_price,
        'line_total', roi.total_price
      )
    ) AS items
  FROM restaurant_order_items roi
  LEFT JOIN restaurant_menu_items rmi ON rmi.id = roi.menu_item_id
  GROUP BY roi.order_id
) backfill
WHERE vr.order_id = backfill.order_id
  AND (vr.void_items IS NULL OR vr.void_items = '[]'::jsonb);


