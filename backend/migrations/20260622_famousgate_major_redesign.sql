CREATE OR REPLACE FUNCTION check_opening_stock_complete(p_shift_id UUID)
RETURNS BOOLEAN AS $$
DECLARE
  v_status shift_opening_stock_status%ROWTYPE;
BEGIN
  SELECT * INTO v_status FROM shift_opening_stock_status WHERE shift_id = p_shift_id;
  IF NOT FOUND THEN RETURN FALSE; END IF;
