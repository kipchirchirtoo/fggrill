// Update stock level
router.post('/items/:id/stock', authenticate, authorize(['super_admin', 'manager', 'storekeeper']), async (req, res) => {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    
    const { branch, quantity, adjustment_type, notes } = req.body;

    // Update stock level
    await client.query(
      `UPDATE branch_inventory
       SET quantity = CASE
         WHEN $1 = 'add' THEN quantity + $2
         WHEN $1 = 'subtract' THEN GREATEST(0, quantity - $2)
         ELSE $2
       END
       WHERE item_id = $3 AND branch = $4`,
      [adjustment_type, quantity, req.params.id, branch]
    );

    // Record adjustment
    await client.query(
      `INSERT INTO inventory_adjustments (item_id, branch, quantity, adjustment_type, notes, created_by)
       VALUES ($1, $2, $3, $4, $5, $6)`,
      [req.params.id, branch, quantity, adjustment_type, notes, req.user.id]
    );

    await client.query('COMMIT');
    res.json({ message: 'Stock level updated successfully' });
  } catch (error) {
    await client.query('ROLLBACK');
    console.error('Error updating stock level:', error);
    res.status(500).json({ error: 'Failed to update stock level' });
  } finally {
    client.release();
  }
});

