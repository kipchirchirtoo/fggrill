// Create stock transfer
router.post('/transfers', authenticate, authorize(['super_admin', 'manager', 'storekeeper']), async (req, res) => {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    
    const { from_branch, to_branch, items, notes } = req.body;

    const transferResult = await client.query(
      `INSERT INTO stock_transfers (from_branch, to_branch, notes, requested_by)
       VALUES ($1, $2, $3, $4)
       RETURNING id`,
      [from_branch, to_branch, notes, req.user.id]
    );

    const transferId = transferResult.rows[0].id;

    for (const item of items) {
      await client.query(
        `INSERT INTO stock_transfer_items (transfer_id, item_id, quantity)
         VALUES ($1, $2, $3)`,
        [transferId, item.item_id, item.quantity]
      );
    }

    await client.query('COMMIT');
    res.status(201).json({ id: transferId });
  } catch (error) {
    await client.query('ROLLBACK');
    console.error('Error creating stock transfer:', error);
    res.status(500).json({ error: 'Failed to create stock transfer' });
  } finally {
    client.release();
  }
});

// Approve stock transfer
router.post('/transfers/:id/approve', authenticate, authorize(['super_admin', 'manager']), async (req, res) => {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    
    // Update transfer status
    await client.query(
      `UPDATE stock_transfers
       SET status = 'approved', approved_by = $1, approved_at = NOW()
       WHERE id = $2`,
      [req.user.id, req.params.id]
    );

    // Get transfer details
    const transfer = await client.query(
      `SELECT * FROM stock_transfers WHERE id = $1`,
      [req.params.id]
    );

    // Update stock levels
    const items = await client.query(
      `SELECT * FROM stock_transfer_items WHERE transfer_id = $1`,
      [req.params.id]
    );

    for (const item of items.rows) {
      // Reduce stock at source branch
      await client.query(
        `UPDATE branch_inventory
         SET quantity = quantity - $1
         WHERE item_id = $2 AND branch = $3`,
        [item.quantity, item.item_id, transfer.rows[0].from_branch]
      );

      // Increase stock at destination branch
      await client.query(
        `UPDATE branch_inventory
         SET quantity = quantity + $1
         WHERE item_id = $2 AND branch = $3`,
        [item.quantity, item.item_id, transfer.rows[0].to_branch]
      );
    }

    await client.query('COMMIT');
    res.json({ message: 'Stock transfer approved successfully' });
  } catch (error) {
    await client.query('ROLLBACK');
    console.error('Error approving stock transfer:', error);
    res.status(500).json({ error: 'Failed to approve stock transfer' });
  } finally {
    client.release();
  }
});

