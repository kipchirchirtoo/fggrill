const express = require('express');
const router = express.Router();
const { pool } = require('../db');
const { authenticate, authorize } = require('../middleware/auth');

// Get all inventory items
router.get('/items', authenticate, async (req, res) => {
  try {
    const result = await pool.query(
      `SELECT i.*, bi.quantity as current_stock
       FROM inventory_items i
       LEFT JOIN branch_inventory bi ON i.id = bi.item_id AND bi.branch = $1
       ORDER BY i.item_code`,
      [req.query.branch || 'Bomet']
    );
    res.json(result.rows);
  } catch (error) {
    console.error('Error fetching inventory items:', error);
    res.status(500).json({ error: 'Failed to fetch inventory items' });
  }
});

// Get single inventory item details
router.get('/items/:id', authenticate, async (req, res) => {
  try {
    // Get basic item details
    const itemResult = await pool.query(
      `SELECT * FROM inventory_items WHERE id = $1`,
      [req.params.id]
    );

    if (itemResult.rows.length === 0) {
      return res.status(404).json({ error: 'Item not found' });
    }

    // Get stock by branch
    const stockResult = await pool.query(
      `SELECT branch, quantity 
       FROM branch_inventory 
       WHERE item_id = $1`,
      [req.params.id]
    );

    const item = itemResult.rows[0];
    item.stock_by_branch = stockResult.rows;
    item.total_stock = stockResult.rows.reduce((sum, row) => sum + row.quantity, 0);

    res.json(item);
  } catch (error) {
    console.error('Error fetching item details:', error);
    res.status(500).json({ error: 'Failed to fetch item details' });
  }
});

// Get full history (adjustments, transfers, purchases, etc.)
router.get('/items/:id/history-full', authenticate, async (req, res) => {
  try {
    const result = await pool.query(
      `SELECT id, 'adjustment' as type, quantity, branch, notes, created_at, created_by 
       FROM inventory_adjustments WHERE item_id = $1
       UNION ALL
       SELECT id, 'transfer_out' as type, -quantity as quantity, from_branch as branch, notes, created_at, requested_by as created_by
       FROM stock_transfers st JOIN stock_transfer_items sti ON st.id = sti.transfer_id 
       WHERE sti.item_id = $1 AND st.status = 'approved'
       UNION ALL
       SELECT id, 'transfer_in' as type, quantity, to_branch as branch, notes, created_at, requested_by as created_by
       FROM stock_transfers st JOIN stock_transfer_items sti ON st.id = sti.transfer_id 
       WHERE sti.item_id = $1 AND st.status = 'approved'
       UNION ALL
       SELECT id, 'purchase' as type, quantity, branch, notes, created_at, created_by
       FROM purchase_orders po JOIN purchase_order_items poi ON po.id = poi.po_id
       WHERE poi.item_id = $1 AND po.status = 'received'
       ORDER BY created_at DESC`,
      [req.params.id]
    );

    // Enrich with user emails
    for (let row of result.rows) {
      if (row.created_by) {
        const userRes = await pool.query('SELECT email FROM users WHERE id = $1', [row.created_by]);
        row.created_by_email = userRes.rows[0]?.email || 'Unknown';
      }
    }

    res.json(result.rows);
  } catch (error) {
    console.error('Error fetching item history:', error);
    res.status(500).json({ error: 'Failed to fetch item history' });
  }
});

// Create inventory item
router.post('/items', authenticate, authorize(['super_admin', 'manager', 'storekeeper']), async (req, res) => {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    
    const {
      name,
      category,
      subcategory,
      unit,
      reorder_level,
      branches,
      description
    } = req.body;

    // Insert item (item_code will be auto-generated by trigger)
    const itemResult = await client.query(
      `INSERT INTO inventory_items (name, category, subcategory, unit, reorder_level, description, created_by)
       VALUES ($1, $2, $3, $4, $5, $6, $7)
       RETURNING id, item_code`,
      [name, category, subcategory, unit, reorder_level, description, req.user.id]
    );

    // Initialize stock levels for each branch
    for (const branch of branches) {
      await client.query(
        `INSERT INTO branch_inventory (item_id, branch, quantity)
         VALUES ($1, $2, 0)`,
        [itemResult.rows[0].id, branch]
      );
    }

    await client.query('COMMIT');
    res.status(201).json(itemResult.rows[0]);
  } catch (error) {
    await client.query('ROLLBACK');
    console.error('Error creating inventory item:', error);
    res.status(500).json({ error: 'Failed to create inventory item' });
  } finally {
    client.release();
  }
});

